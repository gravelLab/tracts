class ModelComparison:
    """
    A class for comparing tract length distributions generated with the Monoecious Phase-Type implementation (tracts 2.0) and the DemographicModel implementation (tracts 1.0) under the same unbiased setting.
    Both implementations should produce similar result if no sex-biased migration or recombination is present.
    """

    def __init__(self, migration_matrix):
        """
        Initializes the ModelComparison class by creating instances of the Monoecious Phase-Type model and the DemographicModel using the provided migration matrix. 
        """
        self.migration_matrix = migration_matrix
        self.PTD = PhTMonoecious(migration_matrix)
        self.demo = DemographicModel(migration_matrix)

    def compare_proportions(self):
        """
        Checks that the ancestry proportions at generation t=0 are the same for the Monoecious Phase-Type model and the DemographicModel under unbiased migration.
        """
        print(f'DemographicModel proportions at t0: {self.demo.proportions[0]}')
        print(f'Monoecious Phase-Type proportions at t0: {self.PTD.t0_proportions}')
        assert numpy.allclose(self.demo.proportions[0], self.PTD.t0_proportions, atol=0.01)

    def compare_TpopTau(self):
        """
        Checks that the TpopTau values computed by the Monoecious Phase-Type model match those computed by the DemographicModel for all population pairs and generations.
        """
        for tpopTau, result in self.demo.dicTpopTau.items():
            assert self.PTD._get_TpopTau(tpopTau[0], tpopTau[1], tpopTau[2]) == result
        print('TpopTau is equal for Monoecious Phase-Type and DemographicModel. All assertions passed.')

    def compare_models(self, bins, L, population_number):
        """
        Checks that the tract length histograms generated by the Monoecious Phase-Type model and the DemographicModel are similar.
        """
        PTD_hist_tuple = self.PTD.tractlength_histogram_windowed(population_number, bins, L)
        PTD_hist = PTD_hist_tuple[1]
        demo_hist = self.demo.expectperbin([L], population_number, bins)[:-1]
        print(f'\nTractlength histogram from Monoecious Phase-Type: \n{PTD_hist}')
        print(f'\nTractlength histogram from DemographicModel: \n{numpy.array(demo_hist)}')
        assert numpy.allclose(PTD_hist, numpy.array(demo_hist), atol=0.01)

   







