def compare_normalization_factors(migration_matrix, Ls, population_number):
    """
    Checks that the normalization factor Z computed by the Monoecious Phase-Type model matches the Z computed by the DemographicModel for a
    range of chromosome lengths, and that the expected number of tracts per bin from the DemographicModel matches
    the expected number of tracts per bin from the Phase-Type distribution when scaled by Z.
    """

    PTD = PhTMonoecious(migration_matrix)
    demo = DemographicModel(migration_matrix)
    tracts_z = demo.Z(Ls, population_number)
    phase_type_z = numpy.array([PTD.normalization_factor([L], PTD.transition_matrices[population_number],
                                                         PTD.inverse_S0_list[population_number],
                                                         PTD.alpha_list[population_number]) for L in Ls])
    print(f'Z from DemographicModel: {tracts_z}')
    print(f'Z from Monoecious Phase-Type model: {phase_type_z}')
    assert numpy.allclose(tracts_z, phase_type_z)

def verify_PDT(migration_matrix):
    """
    Compares the tract length histograms generated by the Monoecious Phase-Type model and the DemographicModel for a given migration matrix, and checks that they are similar.
    """
    print(f'Migration Matrix:\n{migration_matrix}')

